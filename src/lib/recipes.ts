export function getRecipeBySlug(slug: string): Recipe | undefined {
  return RECIPES.find(r => r.slug === slug && r.published)
}

export function getRecipesByCategory(categorySlug: string): Recipe[] {
  const category = CATEGORIES.find(c => c.slug === categorySlug)
  if (!category) return []
  return RECIPES.filter(r => r.published && r.categories.includes(category.name))
}

export function getFeaturedRecipes(): Recipe[] {
  return RECIPES.filter(r => r.published && r.featured)
}

export function getAllPublishedRecipes(): Recipe[] {
  return RECIPES.filter(r => r.published)
}

export function getCategoryBySlug(slug: string): Category | undefined {
  return CATEGORIES.find(c => c.slug === slug)
}

/** ISO 8601 duration string, e.g. PT1H30M */
export function toIsoDuration(minutes: number): string {
  if (minutes === 0) return 'PT0M'
  const h = Math.floor(minutes / 60)
  const m = minutes % 60
  return `PT${h > 0 ? `${h}H` : ''}${m > 0 ? `${m}M` : ''}`
}
